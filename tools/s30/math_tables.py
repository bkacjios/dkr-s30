#!/usr/bin/env python3
"""The sine and arctangent tables of the game's math library
(src/hasm/ido/math_util.s) as C, for src/s30/game/math_util.c.

Usage: math_tables.py math_util.s out.c
"""
import re
import sys


def main():
    src, out = sys.argv[1], sys.argv[2]
    tables = {}
    name = None
    for line in open(src):
        m = re.match(r"\s*EXPORT\((\w+)\)", line)
        if m:
            name = m.group(1)
            continue
        if line.strip().startswith(".text"):
            break
        m = re.match(r"\s*\.half\s+(.*)", line)
        if m and name is not None:
            tables.setdefault(name, []).extend(v.strip() for v in m.group(1).split(","))
    with open(out, "w") as f:
        f.write("/* Generated by tools/s30/math_tables.py from %s */\n" % src)
        f.write("typedef unsigned short u16;\n")
        for name in ("gSineTable", "gArcTanTable"):
            values = tables[name]
            assert len(values) == 1025, (name, len(values))
            f.write("u16 %s[%d] = {\n" % (name, len(values)))
            for i in range(0, len(values), 16):
                f.write("    " + ", ".join(values[i:i + 16]) + ",\n")
            f.write("};\n")


if __name__ == "__main__":
    main()
