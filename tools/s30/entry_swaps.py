#!/usr/bin/env python3
"""Which fields of each level object entry (include/level_object_entries.h)
are 16 or 32 bits wide, by object behaviour, for src/s30/game/swap.c: object
maps come from the ROM big-endian, and the game reads their entries through
these structs.

The behaviour -> entry struct order is the asset tool's
(tools/dkr_assets_tool_extract.json, /misc/default-object-entries-order).

Usage: entry_swaps.py level_object_entries.h dkr_assets_tool_extract.json out.c
"""
import json
import re
import sys

SIZES = {"u8": 1, "s8": 1, "u16": 2, "s16": 2, "u32": 4, "s32": 4, "f32": 4}


def parse_structs(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    text = re.sub(r"Hint\(\(.*?\)\)", "", text)
    structs = {}
    for m in re.finditer(r"typedef struct (\w+) \{(.*?)\} \1;", text, re.S):
        name, body = m.group(1), m.group(2)
        if "union" in body:
            continue
        fields = []
        for decl in body.split(";"):
            decl = decl.strip()
            if not decl:
                continue
            fm = re.match(r"(\w+)\s+(.+)$", decl)
            if fm is None:
                raise ValueError("%s: can't read %r" % (name, decl))
            ftype = fm.group(1)
            for var in fm.group(2).split(","):
                am = re.match(r"\s*(\w+)\s*(?:\[\s*(\w+)\s*\])?\s*$", var)
                if am is None:
                    raise ValueError("%s: can't read %r" % (name, var))
                count = int(am.group(2), 0) if am.group(2) else 1
                fields.append((ftype, count))
        structs[name] = fields
    return structs


def layout(structs, name):
    """(size, align, [(offset, width)]) of the multi-byte scalars"""
    offset, align, wide = 0, 1, []
    for ftype, count in structs[name]:
        if ftype in SIZES:
            size, falign, inner = SIZES[ftype], SIZES[ftype], [(0, SIZES[ftype])] if SIZES[ftype] > 1 else []
        else:
            size, falign, inner = layout(structs, ftype)
        offset = (offset + falign - 1) // falign * falign
        for i in range(count):
            for o, w in inner:
                wide.append((offset + i * size + o, w))
        offset += size * count
        align = max(align, falign)
    return (offset + align - 1) // align * align, align, wide


def main():
    structs = parse_structs(open(sys.argv[1]).read())
    order = json.load(open(sys.argv[2]))["misc"]["default-object-entries-order"]
    assert len(order) == 128
    with open(sys.argv[3], "w") as f:
        f.write("/* Generated by tools/s30/entry_swaps.py from %s */\n" % sys.argv[1])
        f.write("/* By behaviour: the offsets of 16-bit fields, then of 32-bit fields, each list ended by 0 */\n")
        f.write("const unsigned char gS30EntryWideFields[128][2][32] = {\n")
        for bhv, name in enumerate(order):
            _, _, wide = layout(structs, name)
            halves = [o for o, w in wide if w == 2]
            words = [o for o, w in wide if w == 4]
            assert len(halves) < 32 and len(words) < 32 and 0 not in halves + words
            f.write("    /* %3d %s */ { { %s0 }, { %s0 } },\n" % (
                bhv, name, "".join("%d, " % o for o in halves), "".join("%d, " % o for o in words)))
        f.write("};\n")


if __name__ == "__main__":
    main()
